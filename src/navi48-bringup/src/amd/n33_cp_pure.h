inline uint32_t lo32(uint64_t v) { return (uint32_t)v; }
inline uint32_t hi32(uint64_t v) { return (uint32_t)(v >> 32); }
inline uint32_t doorbell_control(uint32_t mode) { return mode == kModeDb ? kDbControl : 0; }

// ---- Shader (D6): the blob is pinned by the values build-shader.sh generated with it -----------------------------
constexpr uint32_t kShaderBytes = SHADER_STORE_MAGIC_GFX11_BYTES;
constexpr uint32_t kRsrc1 = SHADER_STORE_MAGIC_GFX11_RSRC1, kRsrc2 = SHADER_STORE_MAGIC_GFX11_RSRC2,
                   kRsrc3 = SHADER_STORE_MAGIC_GFX11_RSRC3;
constexpr uint8_t kShaderSha256[32] = SHADER_STORE_MAGIC_GFX11_SHA256;
constexpr uint32_t kEndpgm = 0xBFB00000u;                 // s_endpgm, the code page's fill (R1)
inline bool blob_ok(uint64_t size, const uint8_t digest[32]) {
	if (size != kShaderBytes || size % 4) return false;
	for (int i = 0; i < 32; i++) if (digest[i] != kShaderSha256[i]) return false;
	return true;
}

// ---- Packets (PM4 type 3, nvd.h; no SHADER_TYPE bit on a MEC queue) ---------------------------------------------
constexpr uint32_t pkt3(uint32_t op, uint32_t n) { return (3u << 30) | ((n & 0x3FFFu) << 16) | ((op & 0xFFu) << 8); }
constexpr uint32_t kOpNop = 0x10, kOpDispatchDirect = 0x15, kOpWriteData = 0x37, kOpEventWrite = 0x46,
                   kOpReleaseMem = 0x49, kOpIndirectBuffer = 0x3F, kOpAcquireMem = 0x58, kOpSetShReg = 0x76, kOpSetUconfigReg = 0x79;
constexpr uint32_t kNop = pkt3(kOpNop, 0x3FFF);          // one-dword NOP 0xFFFF1000 (gfx_v11_0.c:7130), also the ring fill
constexpr uint32_t kShRegStart = 0x2C00, kUconfigStart = 0xC000;
constexpr uint32_t kWriteDataCtl = (5u << 8) | (1u << 20);   // DST_SEL 5 (memory), WR_CONFIRM, ENGINE_SEL 0
constexpr uint32_t kInitiator = (1u << 0) | (1u << 2) | (1u << 6) | (1u << 15);   // 0x8045
constexpr uint32_t kCsPartialFlush = 7u | (4u << 8);     // EVENT_TYPE 7, EVENT_INDEX 4
// RELEASE_MEM dword 1: CACHE_FLUSH_AND_INV_TS_EVENT 0x14, index 5, GLM_WB, GLM_INV, GL2_WB (optional), SEQ,
// CACHE_POLICY 3 (gfx_v11_0.c:6078-6109): 0x06603514 with GL2_WB, 0x06403514 without (K5a, D12).
constexpr uint32_t kGl2Wb = 1u << 21;
constexpr uint32_t kRelMemBase = 0x14u | (5u << 8) | (1u << 12) | (1u << 13) | (1u << 22) | (3u << 25);
constexpr uint32_t kRelMemData = 1u << 29;               // DATA_SEL 1 (32-bit), INT_SEL 0, DST_SEL 0

inline uint32_t pkt_set_uconfig(uint32_t *p, uint32_t reg, uint32_t v) {      // K2 (gfx_v11_0.c:600-603)
	p[0] = pkt3(kOpSetUconfigReg, 1); p[1] = reg - kUconfigStart; p[2] = v;
	return 3;
}
inline uint32_t pkt_write_data(uint32_t *p, uint64_t mc, uint32_t v) {      // K3 (gfx_v11_0.c:653-658)
	p[0] = pkt3(kOpWriteData, 3); p[1] = kWriteDataCtl; p[2] = lo32(mc) & ~3u; p[3] = hi32(mc); p[4] = v;
	return 5;
}
inline uint32_t pkt_release_mem(uint32_t *p, uint64_t mc, uint32_t seq, bool gl2wb) {
	p[0] = pkt3(kOpReleaseMem, 6); p[1] = kRelMemBase | (gl2wb ? kGl2Wb : 0); p[2] = kRelMemData;
	p[3] = lo32(mc) & ~3u; p[4] = hi32(mc); p[5] = seq; p[6] = 0; p[7] = 0;
	return 8;
}
inline uint32_t set_sh(uint32_t *p, uint32_t reg, const uint32_t *v, uint32_t n) {
	p[0] = pkt3(kOpSetShReg, n); p[1] = reg - kShRegStart;
	for (uint32_t i = 0; i < n; i++) p[2 + i] = v[i];
	return 2 + n;
}
// K4 and K5a: the SET_SH_REG runs, DISPATCH_DIRECT 1x1x1, CS_PARTIAL_FLUSH and the fence. 41 dwords.
inline uint32_t pkt_dispatch(uint32_t *p, uint64_t codeMc, uint64_t resultMc, uint64_t fenceMc, uint32_t seq, bool gl2wb) {
	uint32_t n = 0;
	const uint32_t pgm[2] = { lo32(codeMc >> 8), lo32(codeMc >> 40) }, rsrc[2] = { kRsrc1, kRsrc2 }, zero = 0, r3 = kRsrc3;
	const uint32_t thr[3] = { kResultDw, 1, 1 }, ud[2] = { lo32(resultMc), hi32(resultMc) };
	n += set_sh(p + n, kComputePgmLo, pgm, 2);
	n += set_sh(p + n, kComputeRsrc1, rsrc, 2);
	n += set_sh(p + n, kComputeResLimits, &zero, 1);
	n += set_sh(p + n, kComputeTmpring, &zero, 1);
	n += set_sh(p + n, kComputeRsrc3, &r3, 1);
	n += set_sh(p + n, kComputeNumX, thr, 3);
	n += set_sh(p + n, kComputeUserData0, ud, 2);
	p[n++] = pkt3(kOpDispatchDirect, 3); p[n++] = 1; p[n++] = 1; p[n++] = 1; p[n++] = kInitiator;
	p[n++] = pkt3(kOpEventWrite, 0); p[n++] = kCsPartialFlush;
	n += pkt_release_mem(p + n, fenceMc, seq, gl2wb);
	return n;
}

// ---- X4a (step 7): the same streams as gfx10.3 PM4, for xlat12_*translate_level(11, ...) -------------------------
// Every packet but two register values is the same on gfx10.3: the COMPUTE_* addresses (gc_10_3_0_offset.h and
// gc_11_0_0_offset.h, X1's table), SET_SH_REG, DISPATCH_DIRECT and its initiator bits, EVENT_WRITE CS_PARTIAL_FLUSH 7,
// WRITE_DATA (nvd.h, used unchanged by gfx_v10_0.c:4098 and gfx_v11_0.c:654) and RELEASE_MEM dword 1 (gfx_v10_0.c:8721
// and gfx_v11_0.c:6078 emit the same bits from the shared nvd.h; Mesa pkt3.json RELEASE_MEM_OP and _gfx11 agree on
// bits 12 to 23, gfx11 adds GLK_WB at 24, unused here).
// COMPUTE_PGM_RSRC3 and COMPUTE_TMPRING_SIZE are FIELD_REPACK (xlat12_repack_gfx11.h). The gfx10.3 value is the
// native value in gfx10.3 fields (Mesa gfx103.json:11786, :11831 against gfx11.json:10703, :10758):
//   RSRC3: SHARED_VGPR_CNT [3:0] is shared; gfx11's INST_PREF_SIZE [9:4], TRAP_ON_START, TRAP_ON_END, IMAGE_OP [31]
//          have no gfx10.3 source, so a native value using them cannot be expressed (refused at compile time).
//   TMPRING_SIZE: WAVES [11:0] shared; WAVESIZE is [24:12] on gfx10.3, [26:12] on gfx11, so bits 25 and 26 cannot be.
constexpr uint32_t kRsrc3G103 = kRsrc3 & 0xFu;
constexpr uint32_t kTmpringNative = 0, kTmpringG103 = kTmpringNative & 0x1FFFFFFu;
static_assert(kRsrc3G103 == kRsrc3, "kRsrc3 uses a gfx11-only COMPUTE_PGM_RSRC3 field: X4's oracle must allow it");
static_assert(kTmpringG103 == kTmpringNative, "TMPRING_SIZE.WAVESIZE wider than gfx10.3's 13 bits");
// K4 as gfx10.3 PM4. Kept apart from pkt_dispatch so the hardware-proven builder stays the oracle. 41 dwords.
inline uint32_t pkt_dispatch_g103(uint32_t *p, uint64_t codeMc, uint64_t resultMc, uint64_t fenceMc, uint32_t seq,
                                  bool gl2wb) {
	uint32_t n = 0;
	const uint32_t pgm[2] = { lo32(codeMc >> 8), lo32(codeMc >> 40) }, rsrc[2] = { kRsrc1, kRsrc2 }, zero = 0;
	const uint32_t r3 = kRsrc3G103, tmp = kTmpringG103;
	const uint32_t thr[3] = { kResultDw, 1, 1 }, ud[2] = { lo32(resultMc), hi32(resultMc) };
	n += set_sh(p + n, kComputePgmLo, pgm, 2);
	n += set_sh(p + n, kComputeRsrc1, rsrc, 2);
	n += set_sh(p + n, kComputeResLimits, &zero, 1);
	n += set_sh(p + n, kComputeTmpring, &tmp, 1);
	n += set_sh(p + n, kComputeRsrc3, &r3, 1);
	n += set_sh(p + n, kComputeNumX, thr, 3);
	n += set_sh(p + n, kComputeUserData0, ud, 2);
	p[n++] = pkt3(kOpDispatchDirect, 3); p[n++] = 1; p[n++] = 1; p[n++] = 1; p[n++] = kInitiator;
	p[n++] = pkt3(kOpEventWrite, 0); p[n++] = kCsPartialFlush;
	n += pkt_release_mem(p + n, fenceMc, seq, gl2wb);
	return n;
}
// The shader-free stream: WRITE_DATA of v to mc, then the fence. 13 dwords. Native gfx11 form.
inline uint32_t pkt_wd(uint32_t *p, uint64_t mc, uint32_t v, uint64_t fenceMc, uint32_t seq, bool gl2wb) {
	uint32_t n = pkt_write_data(p, mc, v);
	return n + pkt_release_mem(p + n, fenceMc, seq, gl2wb);
}
// Its gfx10.3 form: both packets encode the same on gfx10.3 (above), so the same dwords.
inline uint32_t pkt_wd_g103(uint32_t *p, uint64_t mc, uint32_t v, uint64_t fenceMc, uint32_t seq, bool gl2wb) {
	return pkt_wd(p, mc, v, fenceMc, seq, gl2wb);
}

// ---- X4b (step 7): cp xib <stream>, a fixed gfx10.3 stream translated in the kext and submitted as W1's cp submit ----
// Stream 0 is T1/W1's native K4 (no translation). Streams 1 and 2 are built here as gfx10.3, translated by
// xlat12_ib_translate_level(11, ...) into the IB, and compared dword for dword with the native builder (refusal 65).
// No PM4 comes from userspace: it names a stream number only. Addresses are T1/W1's: code page, host page B, fence.
enum Xib : uint32_t { kXibK4 = 0, kXibWd = 1, kXibDispatch = 2,
                      kXibBoCopy = 3, kXibBoFault = 4,     // 3, 4: W2's bo copy / bo fault (n33_bo_pure.h), not cp xib's
                      kXibVmCopy = 5, kXibVmDispatch = 6, kXibVmFault = 7,   // W2V: VMID-8 streams (n33_vm_pure.h)
                      kXibVmUser = 8 };   // W3: the caller's IB in a VMID-8 BO; the kext does not build it (Mesa did)
constexpr bool is_vm_stream(uint32_t s) { return s == kXibVmCopy || s == kXibVmDispatch || s == kXibVmFault; }
constexpr bool is_fault_stream(uint32_t s) { return s == kXibBoFault || s == kXibVmFault; }
constexpr uint32_t kXibCap = 64;              // X4a: the worst translated length of these streams is 53 dwords
constexpr uint32_t kHostXibWd = kHostK3;      // wd's target in host page B (K3's word, pre-filled before each submit)
constexpr uint32_t kXibSame = 0xFFFFFFFFu;    // xib_first_diff: no difference
inline bool valid_xib(uint32_t s) { return s == kXibWd || s == kXibDispatch; }
inline uint32_t xib_wd_value(uint32_t seq) { return kMagic + seq; }
// Dwords the stream stores in host page B: wd writes one, the dispatches (K4 and xib 2) write 32.
constexpr uint32_t xib_want(uint32_t stream) {
	// W2/W2V: a copy stores 16 samples, the dispatch 32 dwords, a fault nothing.
	if (stream == kXibWd) return 1;
	if (stream == kXibBoCopy || stream == kXibVmCopy) return 16;
	if (stream == kXibBoFault || stream == kXibVmFault) return 0;
	if (stream == kXibVmUser) return 0;   // W3: the kext checks only the fence and the queue health; Mesa reads its own BO
	return kResultDw;   // K4, xib dispatch and vm dispatch: 32 dwords
}
// The gfx10.3 input of stream 1 or 2 (0 dwords for any other stream).
inline uint32_t xib_g103(uint32_t s, uint32_t *p, const Geo &g, uint32_t seq) {
	if (s == kXibWd) return pkt_wd_g103(p, g.hostB + kHostXibWd, xib_wd_value(seq), g.hostB + kHostFence4, seq, true);
	if (s == kXibDispatch) return pkt_dispatch_g103(p, g.code, g.hostB, g.hostB + kHostFence4, seq, true);
	return 0;
}
// The native gfx11 oracle for the same stream; stream 0 is T1/W1's K4 exactly as they build it.
inline uint32_t xib_native(uint32_t s, uint32_t *p, const Geo &g, uint32_t seq) {
	if (s == kXibWd) return pkt_wd(p, g.hostB + kHostXibWd, xib_wd_value(seq), g.hostB + kHostFence4, seq, true);
	if (s == kXibDispatch || s == kXibK4) return pkt_dispatch(p, g.code, g.hostB, g.hostB + kHostFence4, seq, true);
	return 0;
}
// First dword index where a and b differ (a length difference differs at the shorter length), or kXibSame.
inline uint32_t xib_first_diff(const uint32_t *a, uint32_t an, const uint32_t *b, uint32_t bn) {
	const uint32_t n = an < bn ? an : bn;
	for (uint32_t i = 0; i < n; i++) if (a[i] != b[i]) return i;
	return an == bn ? kXibSame : n;
}

// Pad with one-dword NOPs to the next 256-dword boundary, as amdgpu_ring_commit. Returns the padded length.
inline uint32_t pad(uint32_t *p, uint32_t n) {
	while (n % kSubmitDw) p[n++] = kNop;
	return n;
}
// T1 (step 7): the INDIRECT_BUFFER control dword, identical on gfx11 and gfx12 (gfx_v11_0.c:6043-6076; nvd.h:224-241):
// INDIRECT_BUFFER_VALID (bit 23) | IB_SIZE (bits 19:0) | VMID (bits 27:24); no CHAIN, PRE_ENB or CACHE_POLICY (D3).
constexpr uint32_t kIbValid = 1u << 23;
inline uint32_t ib_control(uint32_t sizeDw, uint32_t vmid) { return kIbValid | (sizeDw & 0xFFFFFu) | ((vmid & 0xFu) << 24); }
// PACKET3(INDIRECT_BUFFER, 2): header 0xC0023F00, ib_lo (dword-aligned), ib_hi, control. 4 dwords.
// ACQUIRE_MEM before each IB, as gfx_v11_0_emit_mem_sync (gfx_v11_0.c:6848): write back and invalidate GL2, GLM, and
// invalidate GL1, GLV, GLK, GLI over the whole range. Without it the CP re-ran a stale VRAM IB from GL2 after the CPU
// rewrote it through the BAR (W2V V3b, 2026-10-18). 8 dwords.
constexpr uint32_t kGcrSync = (1u << 14) | (1u << 15) | (1u << 5) | (1u << 4) | (1u << 9) | (1u << 8) | (1u << 7) | (1u << 0);
static_assert(kGcrSync == 0xC3B1u, "GL2_INV GL2_WB GLM_INV GLM_WB GL1_INV GLV_INV GLK_INV GLI_INV (nvd.h:458-488)");
inline uint32_t pkt_acquire_mem(uint32_t *p) {
	p[0] = pkt3(kOpAcquireMem, 6); p[1] = 0; p[2] = 0xFFFFFFFFu; p[3] = 0xFFFFFFu; p[4] = 0; p[5] = 0; p[6] = 0xA; p[7] = kGcrSync;
	return 8;
}
inline uint32_t pkt_indirect_buffer(uint32_t *p, uint64_t ibMc, uint32_t sizeDw, uint32_t vmid) {
	p[0] = pkt3(kOpIndirectBuffer, 2); p[1] = lo32(ibMc) & ~3u; p[2] = hi32(ibMc); p[3] = ib_control(sizeDw, vmid);
	return 4;
}

// ---- MQD (struct v11_compute_mqd, gfx_v11_0_compute_mqd_init, gfx_v11_0.c:4337-4479) -----------------------------
// The header words and dwords 128 to 183 with the values K1b writes, from the reset defaults K0 checks. The CP reads
// it only for save and restore; K6's drain may write it.
constexpr uint32_t kMqdDw = 256;
inline void mqd_build(uint32_t mode, uint64_t fbBase, uint32_t *m) {
	const Geo g = geo(fbBase);
	for (uint32_t i = 0; i < kMqdDw; i++) m[i] = 0;
	m[0] = 0xC0310800u;                                    // header
	m[11] = 1;                                             // compute_pipelinestat_enable
	m[23] = m[24] = m[26] = m[27] = 0xFFFFFFFFu;           // compute_static_thread_mgmt_se0..3
	m[44] = m[45] = m[46] = m[47] = 0xFFFFFFFFu;           // se4..7 (AM ip.py:375; 2 SEs exist)
	m[32] = 7;                                             // compute_misc_reserved
	m[mqd_dw(kMqdBase)] = lo32(g.mqd) & ~3u; m[mqd_dw(kMqdBaseHi)] = hi32(g.mqd);
	m[mqd_dw(kHqdActive)] = 1;
	m[mqd_dw(kHqdPersistent)] = (kPersistentDefault & ~kPreloadMask) | (kPreloadSize << 8);
	m[mqd_dw(kHqdPipePrio)] = kPipePrio; m[mqd_dw(kHqdQueuePrio)] = kQueuePrio; m[mqd_dw(kHqdQuantum)] = kQuantum;
	m[mqd_dw(kPqBase)] = lo32(g.ring >> 8); m[mqd_dw(kPqBaseHi)] = hi32(g.ring >> 8);
	m[mqd_dw(kRptrReport)] = lo32(g.rptr) & ~3u; m[mqd_dw(kRptrReportHi)] = hi32(g.rptr) & 0xFFFFu;
	m[mqd_dw(kWptrPoll)] = lo32(g.wptr) & ~3u; m[mqd_dw(kWptrPollHi)] = hi32(g.wptr) & 0xFFFFu;
	m[mqd_dw(kPqDoorbell)] = doorbell_control(mode);
	m[mqd_dw(kPqControl)] = (kPqControlDefault & ~kPqMask) | kPqValue;
	m[mqd_dw(kIbControl)] = kIbControlDefault;
	m[mqd_dw(kMqdControl)] = kMqdControlDefault & ~kMqdVmidMask;
	m[mqd_dw(kEopBase)] = lo32(g.eop >> 8); m[mqd_dw(kEopBaseHi)] = hi32(g.eop >> 8);
	m[mqd_dw(kEopControl)] = (kEopControlDefault & ~kEopSizeMask) | kEopSize;
}

// ---- Refusal reasons. 43, 47 and 50 keep their step-5 meanings; 54 to 61 are new. --------------------------------
enum Why : uint32_t {
	kWhyOk = 0,
	kWhyGcDown = 43,     // AUTOLOAD_RLC not successful in this load, BOOTLOAD_COMPLETE clear, or CP_STAT not 0
	kWhyOverlap = 47,    // a step-6 VRAM page overlaps a live DMCUB window or another protected range
	kWhyFault = 50,      // GCVM_L2_PROTECTION_FAULT_STATUS not 0 before the step
	kWhyOrder = 54,      // start before C1 or G6, while SDMA0 runs, or twice in one mode; test before start, after
	                     // stop, or before the previous test; stop with no queue; plan or journal full
	kWhyState = 55,      // CP_MEC_RS64_CNTL not as C1 (or a K6) left it, CP_HQD_ACTIVE already 1, or CP_HQD_ERROR set
	kWhyLatched = 56,    // D8: a test failed, a start after a hard failure, or this mode already timed out
	kWhyGart = 57,       // GART slot 1 could not be bound to host page B, or a hub flush did not acknowledge
	kWhyModeSwitch = 58, // a start in the other mode while the queue runs: `cp stop` first
	kWhyDoorbell = 59,   // db mode: BAR2 not mapped (or IOPCIFamily and config space disagree), smaller than 0x20
	                     // bytes, or the NBIO doorbell aperture not enabled
	kWhyArg = 60,        // not a test number (1 to 5) or a mode (mmio, db)
	kWhyBlob = 61,       // the embedded gfx11 shader blob is not the pinned one (size or sha256)
	kWhyIbOrder = 62,    // T1 (step 7): cp ib or cp submit before cp start, before a plain ring packet (K2/K3) succeeded
	                     // since the start, or (cp submit) while a previous submit has not been waited on
	kWhyIbOverlap = 63,  // T1: the IB page overlaps a live DMCUB window or another protected range
	kWhyNoSubmit = 64,   // W1 (step 7): cp waitseq with no outstanding cp submit in this load, or a seqno that is not
	                     // the outstanding one
	kWhyXibMismatch = 65,// X4b (step 7): cp xib's translated stream differs from the native builder, or xlat12 refused it
};

// X4b: 65 on a translator error (status not 0) or any difference from the native stream; an empty stream differs.
inline uint32_t xib_verdict(uint32_t status, const uint32_t *out, uint32_t len, const uint32_t *native, uint32_t nn) {
	if (status || !nn || xib_first_diff(out, len, native, nn) != kXibSame) return kWhyXibMismatch;
	return kWhyOk;
}

// ---- Plans (step 5's Entry and read-back rule, plus three ops of its own) ---------------------------------------
// kOpSleepMs: sleep value ms. kOpPoll: read reg until (reg & mask) == 0, up to value ms (0: one read); its outcome is
// recorded, not compared. kOpWIfBusy: a whole-register write that runs only if the last kOpPoll ended with the bits
// still set (K6's reset stage). kOpWIfSet: the same condition, but not counted as the reset stage (K6's drain).
enum Op : uint32_t { kOpSleepMs = 3, kOpPoll = 4, kOpWIfBusy = 5, kOpWIfSet = 6 };
constexpr uint32_t kPlanMax = 64;
constexpr uint32_t kJournalMax = 256;                    // D11: the compute journal, apart from step 5's 192

// K1: (db) NBIO entry 0, then K1a (MEC pipe 0, 1 ms, SH_MEM_CONFIG under VMID 0), then K1b in Linux's
// kiq_init_register order (gfx_v11_0.c:4482-4590, D5). The ACTIVE-is-0 check Linux makes mid-way is the kext's
// pre-start check (code 55). The GRBM_GFX_CNTL writes are recorded, not compared (it reads back 0 on this card).
inline uint32_t k1_plan(uint32_t mode, uint64_t fbBase, Entry *out, uint32_t max, uint32_t *count) {
	*count = 0;
	if (!valid_mode(mode)) return kWhyArg;
	const Geo g = geo(fbBase);
	const bool db = mode == kModeDb;
	const uint32_t all = 0xFFFFFFFFu;
	PlanOut p = { out, max, 0, false };
	if (db) p.add(kOpWInd, kS2aEntry0, kS2aMask, kS2aValue0, kS2aMask);   // nbio gc_doorbell_init, before cp_resume
	p.rmw(kCpMecRs64Cntl, kMecK1aMask, kMecK1aValue);                      // K1a: cp_compute_enable, pipe 0 only (D3)
	p.add(kOpSleepMs, 0, 0, 1, 0);
	p.w(kGrbmGfxCntl, 0, 0);                                               // VMID 0
	p.w(kShMemConfig, kShMemConfigValue, all);
	p.w(kGrbmGfxCntl, 0, 0);
	p.w(kGrbmGfxCntl, kSelQ0, 0);                                          // K1b under ME 1, pipe 0, queue 0
	p.rmw(kPqWptrPollCntl, kPollEn, 0);
	p.w(kEopBase, lo32(g.eop >> 8), all); p.w(kEopBaseHi, hi32(g.eop >> 8), all);
	p.rmw(kEopControl, kEopSizeMask, kEopSize);
	p.w(kPqDoorbell, doorbell_control(mode), all);
	p.w(kMqdBase, lo32(g.mqd) & ~3u, all); p.w(kMqdBaseHi, hi32(g.mqd), all);
	p.rmw(kMqdControl, kMqdVmidMask, 0);
	p.w(kPqBase, lo32(g.ring >> 8), all); p.w(kPqBaseHi, hi32(g.ring >> 8), all);
	p.rmw(kPqControl, kPqMask, kPqValue);
	p.w(kRptrReport, lo32(g.rptr) & ~3u, all); p.w(kRptrReportHi, hi32(g.rptr) & 0xFFFFu, all);
	p.w(kWptrPoll, lo32(g.wptr) & ~3u, all); p.w(kWptrPollHi, hi32(g.wptr) & 0xFFFFu, all);
	if (db) { p.w(kMecDbLower, kMecDbLowerValue, all); p.w(kMecDbUpper, kMecDbUpperValue, all); }
	p.w(kPqDoorbell, doorbell_control(mode), all);
	p.w(kPqWptrLo, 0, all); p.w(kPqWptrHi, 0, all);
	p.w(kHqdVmid, 0, all);
	p.rmw(kHqdPersistent, kPreloadMask, kPreloadSize << 8);
	p.rmw(kHqdActive, kActive, kActive);
	if (db) p.rmw(kPqStatus, kPqStatusDbEn, kPqStatusDbEn);
	p.w(kGrbmGfxCntl, 0, 0);
	if (p.over) return kWhyOrder;
	*count = p.n;
	return kWhyOk;
}

// K6 (D9): drain (only an active queue, as Linux gfx_v11_0.c:4497-4499 and AM ip.py:445-446), then the reset stage only if the queue is still active, then Linux's pointer clears, the doorbell
// off and ACTIVE 0 under the select; in db mode the CP doorbell enable, the MEC range and S2A entry 0 back to what K1
// found; then MEC_HALT (AM's halt_engines; the pipe resets and active bits are left). Unload: the polls read once.
struct Found { uint32_t s2a, dbLower, dbUpper; };
inline uint32_t k6_plan(uint32_t mode, const Found &f, bool unload, Entry *out, uint32_t max, uint32_t *count) {
	*count = 0;
	if (!valid_mode(mode)) return kWhyArg;
	const uint32_t all = 0xFFFFFFFFu, ms = unload ? 0 : 100;
	PlanOut p = { out, max, 0, false };
	p.w(kGrbmGfxCntl, kSelQ0, 0);
	p.add(kOpPoll, kHqdActive, kActive, 0, 0);             // one read: is the queue active?
	p.add(kOpWIfSet, kDequeue, all, 1, 0);                 // DEQUEUE_REQ drain (gfx_v11_0.c:4510-4515)
	p.add(kOpPoll, kHqdActive, kActive, ms, 0);
	p.add(kOpWIfBusy, kDequeue, all, 2, 0);                // reset waves (AM ip.py:447-448)
	p.add(kOpWIfBusy, kSpiQueueReset, all, 1, 0);
	p.add(kOpPoll, kHqdActive, kActive, ms, 0);            // a timeout is tolerated, as AM's (ip.py:452-453)
	p.w(kDequeue, 0, 0);
	p.w(kHqdError, 0, all);                                // a VM fault latches TC_UTCL1_ERROR here; K1 refuses while set (Linux reloads 0 from the MQD, amdgpu_amdkfd_gfx_v11.c:198-200)
	p.w(kPqRptr, 0, 0);
	p.w(kPqWptrLo, 0, all); p.w(kPqWptrHi, 0, all);
	p.w(kPqDoorbell, 0, all);
	p.w(kHqdActive, 0, 0);
	p.w(kGrbmGfxCntl, 0, 0);
	if (mode == kModeDb) {
		p.rmw(kPqStatus, kPqStatusDbEn, 0);
		p.w(kMecDbLower, f.dbLower, all); p.w(kMecDbUpper, f.dbUpper, all);
		p.add(kOpWInd, kS2aEntry0, all, f.s2a, kS2aMask);
	}
	p.rmw(kCpMecRs64Cntl, kMecHalt, kMecHalt);
	if (p.over) return kWhyOrder;
	*count = p.n;
	return kWhyOk;
}

// ---- `cp state`: the global registers it reads (none before GC is up; the S2A entry is not read here) --------------
constexpr uint32_t kStateRegs[] = {
	kCpMecRs64Cntl, kMecInstrPntr, kPqWptrPollCntl, kPqStatus, kMecDbLower, kMecDbUpper, kRlcCpSchedulers, kCpMesCntl,
	kCpStat, kGrbmStatus, kCpcStatus, kScratchReg0, kGcFaultStatus, kGcFaultAddrLo, kGcFaultAddrHi, kCpcIcBaseLo,
};
constexpr uint32_t kStateCount = sizeof kStateRegs / sizeof kStateRegs[0];

// ---- State and gates (D4, D7, D8) -----------------------------------------------------------------------------
struct State {
	bool pagesOwned;        // K1 took the step-6 pages (kind 16); kept until unload
	bool running;           // K1 ran and K6 has not
	uint32_t mode;          // the mode of the running (or last) queue
	uint32_t latch;         // D8
	uint32_t timedOut;      // bit per mode that has had a timeout-only failure in this load
	uint64_t wptrDw;        // dwords committed since the start (the running 64-bit write pointer)
	uint32_t seq;           // last fence sequence sent
	uint32_t testsOk;       // bit n: test n succeeded since the start
	uint32_t starts;        // K1 attempts in this load
	Found found;            // db mode: S2A entry 0 and the MEC doorbell range as K1 found them
	uint32_t k1Grbm;        // GRBM_STATUS at the end of K1, for the dispatch tests' busy check
	bool k5aDataAll;        // K5a's 32 VRAM dwords all landed without GL2_WB
	bool ibOwned;           // T1 (step 7): cp ib took the IB page (kind 17); kept until unload, like pagesOwned
	bool submitPending;     // W1 (step 7): a cp submit is outstanding (kicked, not yet waited); one at a time
	uint32_t submitSeq;     // W1: the RELEASE_MEM seqno cp submit returned
	uint64_t submitWp;      // W1: the ring wptr after that submit, for cp waitseq's rptr_at check
	uint32_t submitRptr0;   // W1: CP_HQD_PQ_RPTR just before the submit kick, for cp waitseq's rptrMoved check
	uint32_t submitStream;  // X4b: the outstanding submit's stream (kXibK4 for cp submit), so cp waitseq checks its stores
};

// K1's MEC check (code 55): C1 leaves 0x40000000; a K6 in this load leaves pipe 0 active as well.
inline bool mec_ready(const State &s, uint32_t mec) {
	return mec == kMecAfterC1 || (s.starts && mec == (kMecAfterC1 | kMecPipe0Active));
}
// K1: argument, GC gate, latch, mode switch, order (D7: C1 and G6 done, SDMA0 queue not running).
inline uint32_t may_start(const State &s, uint32_t mode, bool gcUp, bool c1, bool g6, bool sdmaRunning) {
	if (!valid_mode(mode)) return kWhyArg;
	if (!gcUp) return kWhyGcDown;
	if (s.latch == kLatchHard || (s.timedOut & (1u << mode))) return kWhyLatched;
	if (s.running) return mode == s.mode ? kWhyOrder : kWhyModeSwitch;
	if (!c1 || !g6 || sdmaRunning) return kWhyOrder;
	return kWhyOk;
}
inline void record_start(State &s, uint32_t mode, bool ok) {
	s.running = true; s.mode = mode; s.wptrDw = 0; s.testsOk = 0; s.starts++; s.k5aDataAll = false; s.submitPending = false;
	if (!ok) s.latch = kLatchHard;
}

// K2 to K5b as tests 1 to 5. Test n needs test n - 1 to have succeeded since this start; test 5 (K5b) only when
// K5a's data did not all land. Every submission waits for the CP to consume it, so the ring never fills; K5b is
// the first to wrap the ring offset.
inline bool valid_test(uint32_t n) { return n >= 1 && n <= 5; }
inline uint32_t may_test(const State &s, uint32_t n) {
	if (!valid_test(n)) return kWhyArg;
	if (!s.running) return kWhyOrder;
	if (s.latch != kLatchNone) return kWhyLatched;
	if (n > 1 && !(s.testsOk >> (n - 1) & 1u)) return kWhyOrder;
	if (n == 5 && s.k5aDataAll) return kWhyOrder;
	return kWhyOk;
}
inline uint32_t timeout_us(uint32_t n) { return n == 3 || n == 4 ? 2000000 : 100000; }   // compute_test.cpp:332
inline uint64_t ring_off(uint64_t wptrDw) { return (wptrDw % kRingDw) * 4; }               // byte offset in the ring
// CP_HQD_PQ_RPTR counts dwords in the ring; compared modulo the ring, so 1024 after K5a reads as 0.
inline bool rptr_at(uint32_t rptr, uint64_t wptrDw) { return (rptr % kRingDw) == (uint32_t)(wptrDw % kRingDw); }

// D8's outcome of one test. Done: the target(s) seen, CP_HQD_PQ_RPTR caught up, the HQD still active, no GC VM fault,
// CP_HQD_ERROR 0. A timeout with nothing else wrong (rptr where it was) is timeout-only; anything else is hard.
struct TestRead { bool seen, rptrOk, active; uint32_t fault, hqdError; bool rptrMoved; };
inline uint32_t outcome(const TestRead &r) {
	if (r.seen && r.rptrOk && r.active && !r.fault && !r.hqdError) return kLatchNone;
	if (!r.seen && r.active && !r.rptrMoved && !r.fault && !r.hqdError) return kLatchTimeout;
	return kLatchHard;
}
inline void record_test(State &s, uint32_t n, uint32_t latch, bool k5aAll = false) {
	s.wptrDw += kSubmitDw;
	if (latch == kLatchNone) { s.testsOk |= 1u << n; if (n == 4) s.k5aDataAll = k5aAll; return; }
	if (latch == kLatchTimeout) s.timedOut |= 1u << s.mode;
	if (latch > s.latch) s.latch = latch;
}

// T1 (step 7): cp ib runs an INDIRECT_BUFFER from the started queue. It needs the queue running, not latched, and a
// plain ring packet (K2 = test 1, or K3 = test 2) already landed since this start, so an IB failure cannot be blamed on
// a queue that never fetched the ring (design "Refusal codes"). A latched queue is 56, not 62, as the hardware gate.
inline uint32_t may_ib(const State &s) {
	if (!s.running) return kWhyIbOrder;
	if (s.latch != kLatchNone) return kWhyLatched;
	if (!(s.testsOk & ((1u << 1) | (1u << 2)))) return kWhyIbOrder;   // neither K2 nor K3 succeeded since the start
	if (s.submitPending) return kWhyIbOrder;   // a W1 submit is still outstanding: no second kick before its waitseq
	return kWhyOk;
}
// Bookkeeping for one T1 kick: like record_test but no test bit is set (T1 is not a numbered ring test). The ring grew
// by one 256-dword submission (the INDIRECT_BUFFER and its NOP pad); the IB itself is not in the ring.
inline void record_ib(State &s, uint32_t latch) {
	s.wptrDw += kSubmitDw;
	if (latch == kLatchTimeout) s.timedOut |= 1u << s.mode;
	if (latch > s.latch) s.latch = latch;
}

// W1 (step 7): cp submit is T1's INDIRECT_BUFFER kick as the first half of the winsys submit->wait contract. It needs
// the same state as cp ib (may_ib), plus only one submit outstanding at a time: a second submit before cp waitseq is
// out of order (62). For W1 the submitted IB is still T1's kext-built K4 stream; a caller-named BO IB comes with W2/W3.
inline uint32_t may_submit(const State &s) {
	uint32_t w = may_ib(s);
	if (w) return w;
	if (s.submitPending) return kWhyIbOrder;
	return kWhyOk;
}
// cp waitseq polls the outstanding submit's RELEASE_MEM fence. It needs the queue running, a submit outstanding and the
// seqno to be that submit's; a stale or wrong seqno is refused (64), not silently waited on.
inline uint32_t may_waitseq(const State &s, uint32_t seq) {
	if (!s.running) return kWhyIbOrder;
	if (!s.submitPending || seq != s.submitSeq) return kWhyNoSubmit;
	return kWhyOk;
}
// record_submit: the ring grew by one 256-dword submission (as record_ib), the fence seqno is live and one submit is
// outstanding. wp is the post-kick wptr and rptr0 the pre-kick CP_HQD_PQ_RPTR, both kept for cp waitseq.
inline void record_submit(State &s, uint32_t seq, uint64_t wp, uint32_t rptr0, uint32_t stream = kXibK4) {
	s.wptrDw += kSubmitDw; s.seq = seq;
	s.submitPending = true; s.submitSeq = seq; s.submitWp = wp; s.submitRptr0 = rptr0; s.submitStream = stream;
}
// X4b: cp xib is cp submit with a translated stream, so it has cp submit's gate (62, 56) and shares its seqno, one
// outstanding submit and cp waitseq. A stream other than 1 or 2 is 60.
inline uint32_t may_xib(const State &s, uint32_t stream) {
	if (!valid_xib(stream)) return kWhyArg;
	return may_submit(s);
}
// record_waitseq: the wait consumed the outstanding submit; the latch is carried exactly as record_ib carries it (a
// timeout marks the mode, a hard failure latches). The wptr already grew at submit, so it is not advanced again.
inline void record_waitseq(State &s, uint32_t latch) {
	s.submitPending = false;
	if (latch == kLatchTimeout) s.timedOut |= 1u << s.mode;
	if (latch > s.latch) s.latch = latch;
}

// K6: allowed whenever the queue runs, latched or not. A stop clears a timeout-only latch; a hard latch stays.
inline uint32_t may_stop(const State &s) { return s.running ? kWhyOk : kWhyOrder; }
inline void record_stop(State &s, bool ok) {
	s.running = false; s.wptrDw = 0; s.testsOk = 0; s.submitPending = false;
	if (s.latch == kLatchTimeout) s.latch = kLatchNone;
	if (!ok) s.latch = kLatchHard;
}

enum Phase : uint32_t { kPhaseK1 = 1, kPhaseK6 = 2 };

