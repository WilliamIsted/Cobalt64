#!/usr/bin/env python3
"""Generate n33_fb_slots.h: the exported IOFramebuffer methods the N33 layout gate pins.
Usage: gen_fb_slots.py <IOGraphicsFamily binary> <out.h>
Fails (exit 1) unless every method matches exactly one exported text symbol."""
import hashlib, subprocess, sys

# slot index -> method name (aux leaves.py FB_EXTRA; the SDK header order)
SLOTS = [(184, 'start'), (310, 'getVRAMRange'), (311, 'enableController'), (319, 'setDisplayMode'),
         (322, 'getStartupDisplayMode'), (325, 'setAttribute'), (326, 'getAttribute'),
         (330, 'getConnectionCount'), (331, 'setAttributeForConnection'),
         (332, 'getAttributeForConnection'), (344, 'hasDDCConnect'), (345, 'getDDCBlock')]

def main():
    binary, out = sys.argv[1], sys.argv[2]
    nm = subprocess.run(['nm', '-gU', '-arch', 'x86_64', binary], capture_output=True, text=True, check=True).stdout
    syms = [l.split() for l in nm.splitlines()]
    syms = [s for s in syms if len(s) == 3 and s[1] == 'T']
    names = [s[2] for s in syms]
    dem = subprocess.run(['c++filt'], input='\n'.join(names) + '\n', capture_output=True, text=True, check=True).stdout.splitlines()
    assert len(dem) == len(names)
    lines = ['// GENERATED by tools/n33/gen_fb_slots.py. DO NOT EDIT.',
             '// source: %s' % binary,
             '// sha256: %s' % hashlib.sha256(open(binary, 'rb').read()).hexdigest(),
             '#pragma once', '#include <stdint.h>']
    slots, addrs = [], []
    for slot, name in SLOTS:
        hits = [n for n, d in zip(names, dem) if d.startswith('IOFramebuffer::%s(' % name)]
        if len(hits) != 1:
            print('FAIL: %s matched %d symbols: %s' % (name, len(hits), hits), file=sys.stderr)
            sys.exit(1)
        lines.append('extern "C" void n33_pin_%s() __asm__("%s");' % (name, hits[0]))
        slots.append(str(slot)); addrs.append('(uintptr_t)&n33_pin_%s' % name)
    lines.append('static const uint16_t kN33FbPinSlot[] = { %s };' % ', '.join(slots))
    lines.append('#define N33_FB_PIN_ADDRS { %s }' % ', '.join(addrs))
    open(out, 'w').write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main()
